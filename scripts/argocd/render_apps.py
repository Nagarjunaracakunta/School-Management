#!/usr/bin/env python3
"""Generates the Argo CD objects for every environment from ONE description, so dev, stage and prod cannot drift apart.

    scripts/argocd/render_apps.py                 # write argocd/envs/<env>/...
    scripts/argocd/render_apps.py --check         # fail if the committed files differ (CI runs this)
    scripts/argocd/render_apps.py --repo-url https://github.com/acme/school-management.git

Per environment:
  bootstrap/project.yaml   the AppProject: what this environment's Argo CD may deploy, from where, to where
  bootstrap/root.yaml      the "root" Application: apply it ONCE by hand; it then creates everything in apps/
  apps/<name>.yaml         one Application per release: the platform chart, then the six services
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "argocd" / "envs"
DEFAULT_REPO = "https://github.com/OWNER/school-management.git"  # a PLACEHOLDER: replace with your repository
ENVIRONMENTS = ["dev", "stage", "prod"]
SERVER = "https://kubernetes.default.svc"  # each environment has its own cluster, with its own Argo CD inside it

# (release name, chart, sync wave). Lower waves must be Healthy before the next wave starts.
#   0 platform: database roles and shared objects      1 auth, student: others call them      2 everything else
RELEASES = [
    ("platform", "school-platform", 0),
    ("auth", "school-service", 1),
    ("student", "school-service", 1),
    ("admission", "school-service", 2),
    ("fee", "school-service", 2),
    ("attendance", "school-service", 2),
    ("notification", "school-service", 2),
]

HEADER = "# GENERATED by scripts/argocd/render_apps.py - do not edit by hand: change the script and run it again.\n"


def namespace(env: str) -> str:
    return f"school-{env}"


def dump(obj: dict) -> str:
    return HEADER + yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=120)


def project(env: str, repo: str) -> dict:
    return {
        "apiVersion": "argoproj.io/v1alpha1",
        "kind": "AppProject",
        "metadata": {"name": f"school-{env}", "namespace": "argocd"},
        "spec": {
            "description": f"School Management Platform, {env}",
            "sourceRepos": [repo],
            "destinations": [{"server": SERVER, "namespace": namespace(env)}],
            # Namespaced objects only, plus the Namespace itself (created by the platform release). No ClusterRole, no CRD.
            "clusterResourceWhitelist": [{"group": "", "kind": "Namespace"}],
            "orphanedResources": {"warn": True},
        },
    }


def root(env: str, repo: str) -> dict:
    return {
        "apiVersion": "argoproj.io/v1alpha1",
        "kind": "Application",
        "metadata": {"name": f"school-{env}-root", "namespace": "argocd"},
        "spec": {
            "project": "default",  # the root lives outside the school project: it creates Applications in the argocd namespace
            "source": {"repoURL": repo, "targetRevision": "main", "path": f"argocd/envs/{env}/apps"},
            "destination": {"server": SERVER, "namespace": "argocd"},
            "syncPolicy": {"automated": {"prune": True, "selfHeal": True}},
        },
    }


def application(env: str, repo: str, name: str, chart: str, wave: int) -> dict:
    if chart == "school-platform":
        value_files = [f"$values/helm/environments/{env}/common.yaml", f"$values/helm/environments/{env}/platform.yaml"]
    else:
        value_files = [
            f"$values/helm/services/{name}.yaml",
            f"$values/helm/environments/{env}/common.yaml",
            f"$values/helm/environments/{env}/{name}.yaml",
        ]
    sync_options = ["ApplyOutOfSyncOnly=true"]
    if name == "platform":
        sync_options.append("CreateNamespace=true")
    spec = {
        "project": f"school-{env}",
        # Two sources: the CHART (templates) and the VALUES (what to run, where). Today both are this repository; the values
        # source is the one that moves to a separate GitOps repository later (ADR 0012).
        "sources": [
            {
                "repoURL": repo,
                "targetRevision": "main",
                "path": f"helm/{chart}",
                "helm": {"releaseName": name, "valueFiles": value_files},
            },
            {"repoURL": repo, "targetRevision": "main", "ref": "values"},
        ],
        "destination": {"server": SERVER, "namespace": namespace(env)},
        "syncPolicy": {
            "syncOptions": sync_options,
            "retry": {"limit": 5, "backoff": {"duration": "15s", "factor": 2, "maxDuration": "3m"}},
        },
        # With an autoscaler the replica count is decided in the cluster, not in Git; do not report that as drift.
        "ignoreDifferences": [{"group": "apps", "kind": "Deployment", "jsonPointers": ["/spec/replicas"]}],
    }
    if name == "platform":
        spec["syncPolicy"]["managedNamespaceMetadata"] = {
            "labels": {
                "pod-security.kubernetes.io/enforce": "restricted",
                "pod-security.kubernetes.io/warn": "restricted",
            }
        }
    if env != "prod":
        # dev and stage follow Git automatically. prod waits for a person to press Sync: the approval step.
        spec["syncPolicy"]["automated"] = {"prune": True, "selfHeal": True}
    metadata = {
        "name": f"school-{env}-{name}",
        "namespace": "argocd",
        "annotations": {"argocd.argoproj.io/sync-wave": str(wave)},
    }
    if env != "prod":  # deleting an Application in prod must never silently delete the running service
        metadata["finalizers"] = ["resources-finalizer.argocd.argoproj.io"]
    return {"apiVersion": "argoproj.io/v1alpha1", "kind": "Application", "metadata": metadata, "spec": spec}


def render(repo: str) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for env in ENVIRONMENTS:
        base = OUT / env
        files[base / "bootstrap" / "project.yaml"] = dump(project(env, repo))
        files[base / "bootstrap" / "root.yaml"] = dump(root(env, repo))
        for name, chart, wave in RELEASES:
            files[base / "apps" / f"{name}.yaml"] = dump(application(env, repo, name, chart, wave))
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo-url", default=DEFAULT_REPO)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    files = render(args.repo_url)
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        extra = [str(p.relative_to(ROOT)) for p in OUT.rglob("*.yaml") if p not in files] if OUT.exists() else []
        if stale or extra:
            print("out of date (run scripts/argocd/render_apps.py):", *stale, *[f"unexpected: {e}" for e in extra], sep="\n  ")
            return 1
        print(f"{len(files)} Argo CD files are up to date")
        return 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(files)} files under argocd/envs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
