#!/usr/bin/env python3
"""Turns `terraform output -json` into the Helm values file for one environment, so nobody copies ARNs by hand.

    cd terraform/environments/dev && terraform output -json > /tmp/outputs-dev.json
    scripts/helm/render-env-values.py dev /tmp/outputs-dev.json [--certificate-arn arn:aws:acm:...]

Writes helm/environments/<env>/common.yaml. It contains no secrets: only names, URLs and ARNs (which point AT the secrets).
No third-party libraries needed.
"""

import argparse
import json
import sys
from pathlib import Path

SERVICES = ["auth", "admission", "student", "fee", "attendance", "notification"]
REQUIRED = [
    "environment", "aws_region", "vpc_cidr_block", "image_registry", "alb_security_group_id", "events_queue_url",
    "notifications_topic_arn", "jwt_public_secret_arn", "jwt_private_secret_arn", "db_secret_arns", "rds_master_secret_arn",
    "kubernetes_namespace",
]
ROOT = Path(__file__).resolve().parents[2]


class OutputError(ValueError):
    pass


def load_outputs(raw: dict) -> dict:
    """`terraform output -json` wraps each value as {"value": ..., "type": ..., "sensitive": ...}."""
    missing = [k for k in REQUIRED if k not in raw or raw[k].get("value") in (None, "", {})]
    if missing:
        raise OutputError(
            "terraform output is missing: " + ", ".join(missing) + ". Has `terraform apply` finished for this environment?"
        )
    return {k: v["value"] for k, v in raw.items()}


def build_values(env: str, out: dict, certificate_arn: str = "") -> dict:
    if out["environment"] != env:
        raise OutputError(f"these outputs are for environment '{out['environment']}', not '{env}'")
    arns = out["db_secret_arns"]
    app = {s: arns.get(f"{s}_app") for s in SERVICES}
    migrator = {s: arns.get(f"{s}_migrator") for s in SERVICES}
    for kind, mapping in (("runtime", app), ("migrator", migrator)):
        absent = [s for s, a in mapping.items() if not a]
        if absent:
            raise OutputError(f"no {kind} database login secret for: {', '.join(absent)}")
        bad = [s for s, a in mapping.items() if not a.startswith("arn:aws:secretsmanager:")]
        if bad:
            raise OutputError(f"the {kind} login for {', '.join(bad)} is not a Secrets Manager ARN")
    if certificate_arn and not certificate_arn.startswith("arn:aws:acm:"):
        raise OutputError("--certificate-arn must be an ACM certificate ARN (arn:aws:acm:...)")
    return {
        "global": {
            "environment": env,
            "region": out["aws_region"],
            "imageRegistry": out["image_registry"],
            "vpcCidr": out["vpc_cidr_block"],
            "eventsQueueUrl": out["events_queue_url"],
            "notificationsTopicArn": out["notifications_topic_arn"],
            "secrets": {
                "dbAppArns": app,
                "dbMigratorArns": migrator,
                "jwtPublicKeyArn": out["jwt_public_secret_arn"],
                "jwtPrivateKeyArn": out["jwt_private_secret_arn"],
                "rdsMasterArn": out["rds_master_secret_arn"],
            },
            "ingress": {
                "groupName": out["kubernetes_namespace"],
                "certificateArn": certificate_arn,
                "securityGroupId": out["alb_security_group_id"],
            },
        }
    }


def to_yaml(data, indent: int = 0) -> str:
    """Minimal YAML writer for nested dicts of strings (JSON strings are valid YAML scalars)."""
    pad = "  " * indent
    lines = []
    for key, value in data.items():
        if isinstance(value, dict):
            lines.append(f"{pad}{key}:")
            lines.append(to_yaml(value, indent + 1))
        else:
            lines.append(f"{pad}{key}: {json.dumps(value)}")
    return "\n".join(lines)


HEADER = """# GENERATED by scripts/helm/render-env-values.py from `terraform output -json`. Do not edit by hand:
# change the Terraform, apply, and generate again. Contains no secrets (ARNs and URLs only).
"""


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("environment", choices=["dev", "stage", "prod"])
    parser.add_argument("outputs_json", type=Path)
    parser.add_argument("--certificate-arn", default="", help="ACM certificate for the load balancer (enables HTTPS)")
    parser.add_argument("--out", type=Path, help="default: helm/environments/<env>/common.yaml")
    args = parser.parse_args(argv)
    try:
        values = build_values(args.environment, load_outputs(json.loads(args.outputs_json.read_text())), args.certificate_arn)
    except (OutputError, json.JSONDecodeError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    target = args.out or ROOT / "helm" / "environments" / args.environment / "common.yaml"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(HEADER + to_yaml(values) + "\n")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
